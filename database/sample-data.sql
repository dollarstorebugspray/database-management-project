    (SELECT pu.unit_cost FROM Purchase pu
     WHERE pu.product_id = oi.product_id AND pu.store_id = o.store_id
       AND pu.purchase_date <= o.order_date
     ORDER BY pu.purchase_date DESC, pu.purchase_id DESC LIMIT 1),
